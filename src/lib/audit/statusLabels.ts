/**
 * src/lib/statusLabels.ts
 *
 * 판정값(Violation['status'])을 담당자가 읽을 말로 옮기는 **단 하나의 표**.
 *
 * [왜 판정값을 그대로 쓰지 않나]
 * 판정값은 규정 문서의 말이다. "금지항목"만 봐서는 무엇이 걸렸는지도, 무엇을 해야
 * 하는지도 알 수 없다. 게다가 두 위반의 실질적인 차이는 **차감 금액을 어떻게 잡느냐**인데
 * (한도초과는 초과분만, 금지항목은 결제 전액) 옛 이름에는 그 차이가 드러나지 않았다.
 * 그래서 라벨은 규정의 말이 아니라 **차감 방식**을 그대로 쓴다.
 *
 * [화면과 엑셀이 같은 말을 쓴다]
 * 화면(src/app/page.tsx)과 엑셀 리포트(src/lib/auditReport.ts)가 이 표를 함께 쓴다.
 * 한쪽만 고치면 담당자가 화면에서는 "전액 차감"을 보고 엑셀에서는 "금지항목"을 보게 된다.
 * 여기만 고치면 두 곳의 말이 항상 같다.
 *
 * [판정 로직과는 무관하다]
 * 필터 동작·건수 집계·차감액 계산은 전부 판정값(key)으로 돌아간다.
 * 이 파일은 보여 줄 말만 정하므로, 얼마든지 고쳐도 판정 결과는 달라지지 않는다.
 */

